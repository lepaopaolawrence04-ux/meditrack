CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(200) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, role ENUM('administrator','receptionist','nurse','doctor') NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS patients (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, dob DATE NOT NULL, sex VARCHAR(20) NOT NULL,
 contact VARCHAR(40) NOT NULL, address VARCHAR(500) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS appointments (
 id INT AUTO_INCREMENT PRIMARY KEY, patient_id INT NOT NULL, doctor_id INT NOT NULL,
 scheduled_at VARCHAR(16) NOT NULL, reason VARCHAR(500) NOT NULL,
 status ENUM('Scheduled','Completed','Cancelled') NOT NULL DEFAULT 'Scheduled',
 scheduled_doctor INT GENERATED ALWAYS AS (CASE WHEN status='Scheduled' THEN doctor_id ELSE NULL END) STORED,
 UNIQUE KEY doctor_slot(scheduled_doctor,scheduled_at),
 FOREIGN KEY(patient_id) REFERENCES patients(id) ON DELETE CASCADE,
 FOREIGN KEY(doctor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS records (
 id INT AUTO_INCREMENT PRIMARY KEY, patient_id INT NOT NULL, doctor_id INT NOT NULL,
 diagnosis TEXT NOT NULL, treatment TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(patient_id) REFERENCES patients(id) ON DELETE CASCADE,
 FOREIGN KEY(doctor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS prescriptions (
 id INT AUTO_INCREMENT PRIMARY KEY, record_id INT NOT NULL, medicine VARCHAR(200) NOT NULL,
 dosage VARCHAR(200) NOT NULL, quantity INT NOT NULL CHECK(quantity > 0), instructions TEXT NOT NULL,
 FOREIGN KEY(record_id) REFERENCES records(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS logs (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, action TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;

